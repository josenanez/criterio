#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""El manual de los comandos de la familia, escrito desde lo que ya los define.

    python3 scripts/manual.py           escribe docs/manual.es.md y docs/manual.md
    python3 scripts/manual.py --check   no escribe; falla si el manual se separó

**El manual no tiene texto propio.** Cada comando ya tiene dueño para cada cosa que el
manual dice de él: qué hace, en la tabla del README de su plugin (una en español y otra
en inglés); qué recibe, qué lee, qué muestra y qué escribe, en el `contratos.json` del
plugin, que `tests/contratos.py` compara contra cada corrida. Un manual escrito a mano
sería una tercera versión de las mismas frases, y el día que un comando cambie quedaría
diciendo lo de antes. Este se regenera, y `--check` rompe la verificación si alguien lo
editó o si un comando cambió sin regenerarlo.

El orden es el de la PMO, el mismo de cada ronda de pruebas: Alba define el producto,
Samuel ejecuta un proyecto, Vera consolida el portafolio y Rostrum lo publica. Dentro de
cada agente, el orden de la tabla de su README.

El contrato está en español. El manual en inglés trae lo que tiene dueño en inglés —qué
hace cada comando y con qué skills— y remite al manual en español para el contrato
completo, en vez de traducirlo aquí y crear una segunda versión sin dueño.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

RAIZ = Path(__file__).resolve().parent.parent
DOCS = RAIZ / "docs"

AGENTES = [
    ("criterio-product", {"es": ("Alba", "un producto"), "en": ("Alba", "a product")}),
    ("criterio-project", {"es": ("Samuel", "un proyecto"), "en": ("Samuel", "a project")}),
    ("criterio-portfolio", {"es": ("Vera", "el portafolio"), "en": ("Vera", "the portfolio")}),
    ("criterio-server", {"es": ("Rostrum", "el portal de todas las familias"), "en": ("Rostrum", "the portal for every family")}),
]

FILA = re.compile(r"^\| `/(criterio-[a-z]+):([a-z-]+)` \| (.+?) \|\s*$")

TXT = {
    "es": {
        "titulo": "# Manual de los comandos de Criterio",
        "intro": ("Los {n} comandos de la familia PMO y de Rostrum, en el orden en que una PMO los usa: Alba define el "
                  "producto, Samuel ejecuta un proyecto, Vera consolida el portafolio y Rostrum lo "
                  "publica. Cada comando se escribe con el prefijo de su plugin; el autocompletado "
                  "hace el resto.\n\n"
                  "Este manual se genera con `scripts/manual.py` desde la tabla del README de cada "
                  "plugin y su `contratos.json`, el mismo contrato que las pruebas comparan contra "
                  "cada corrida. No se edita a mano."),
        "agente": "## {nombre} · {que}",
        "hace": "**Qué hace.** {}",
        "arg": "**Argumento.** {}",
        "lee": "**Lee.** {}",
        "muestra": "**Muestra.** {}",
        "escribe": "**Escribe.** {}",
        "nada": "nada: no escribe",
        "skills": "**Skills.** {}",
    },
    "en": {
        "titulo": "# Criterio command manual",
        "intro": ("The {n} commands of the PMO family and Rostrum, in the order a PMO uses them: Alba defines the product, "
                  "Samuel runs a project, Vera consolidates the portfolio and Rostrum publishes it. "
                  "Each command is typed with its plugin prefix; autocomplete does the rest.\n\n"
                  "This manual is generated by `scripts/manual.py` from each plugin's README table "
                  "and its `contratos.json`. The full contract of each command —what it reads, shows "
                  "and writes— is in Spanish, the language the contract is written and tested in: "
                  "see [manual.es.md](manual.es.md). Do not edit by hand."),
        "agente": "## {nombre} · {que}",
        "hace": "**What it does.** {}",
        "skills": "**Skills.** {}",
    },
}


def tabla(plugin: str, idioma: str) -> list[tuple[str, str]]:
    readme = RAIZ / "plugins" / plugin / ("README.es.md" if idioma == "es" else "README.md")
    filas = []
    for linea in readme.read_text(encoding="utf-8").splitlines():
        m = FILA.match(linea)
        if m and m.group(1) == plugin:
            filas.append((m.group(2), m.group(3).strip()))
    return filas


def lista(xs) -> str:
    """Una ruta va como código —`<estado>` sin comillas se lo come el Markdown como etiqueta—;
    lo demás, como texto."""
    xs = [x for x in (xs or []) if x]
    return "; ".join(f"`{x}`" if ("<" in x or "/" in x) and "`" not in x else seguro(x) for x in xs)


def seguro(x: str) -> str:
    """Fuera del código, un `<` se escapa por la misma razón."""
    partes = x.split("`")
    return "`".join(p if i % 2 else p.replace("<", "&lt;") for i, p in enumerate(partes))


def construir(idioma: str) -> tuple[str, list[str]]:
    t, faltan, partes, n = TXT[idioma], [], [], 0
    for plugin, nombres in AGENTES:
        contratos = json.loads((RAIZ / "plugins" / plugin / "contratos.json").read_text(encoding="utf-8"))["comandos"]
        filas = tabla(plugin, idioma)
        vistos = {c for c, _ in filas}
        for c in sorted(set(contratos) - vistos):
            faltan.append(f"{plugin}:{c} no está en la tabla del README ({idioma})")
        for c in sorted(vistos - set(contratos)):
            faltan.append(f"{plugin}:{c} está en el README ({idioma}) y no tiene contrato")
        nombre, que = nombres[idioma]
        partes.append(t["agente"].format(nombre=nombre, que=que))
        for comando, hace in filas:
            k = contratos.get(comando)
            if k is None:
                continue
            n += 1
            bloque = [f"### `/{plugin}:{comando}`", t["hace"].format(seguro(hace))]
            if idioma == "es":
                ent, sal = k.get("entrada") or {}, k.get("salida") or {}
                if ent.get("argumento"):
                    bloque.append(t["arg"].format(f"`{ent['argumento']}`"))
                if ent.get("lee"):
                    bloque.append(t["lee"].format(lista(ent["lee"])))
                if sal.get("muestra"):
                    bloque.append(t["muestra"].format(seguro(sal["muestra"])))
                bloque.append(t["escribe"].format(lista(sal.get("escribe")) or t["nada"]))
            sk = (k.get("reglas") or {}).get("skills") or []
            if sk:
                bloque.append(t["skills"].format(", ".join(f"**{s}**" for s in sk)))
            partes.append("\n\n".join(bloque))
    texto = "\n\n".join([t["titulo"], t["intro"].format(n=n), *partes]) + "\n"
    return texto, faltan


def main() -> int:
    ap = argparse.ArgumentParser(description="El manual de los comandos, desde el README y el contrato.")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    malos = []
    for idioma, archivo in (("es", DOCS / "manual.es.md"), ("en", DOCS / "manual.md")):
        texto, faltan = construir(idioma)
        malos += faltan
        if a.check:
            if not archivo.is_file() or archivo.read_text(encoding="utf-8") != texto:
                malos.append(f"{archivo.relative_to(RAIZ)} no es el que sale de los README y los contratos: "
                             "corre python3 scripts/manual.py")
        else:
            archivo.write_text(texto, encoding="utf-8")
            print(f"  escrito {archivo.relative_to(RAIZ)} · {texto.count('### ')} comandos")
    for m in malos:
        print("  FALLA", m)
    if not malos and a.check:
        print("  OK    el manual dice lo que dicen los README y los contratos")
    return 1 if malos else 0


if __name__ == "__main__":
    sys.exit(main())
